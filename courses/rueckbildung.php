<p>Ab 01.01.2026 bieten wir auf Grund des zum 01.11.2025 Inkraftgetretenem Hebammenhilfevertrages keine Rückbildungskurse mehr in unserer Praxis an.</p>

<p>Durch die neuen Abrechnungsregelungen bei Kursen ist es uns nicht mehr möglich diese kostendeckend durchzuführen.</p>

<p>Wir bitten um Verständnis,  andernfalls dürfen Sie sich gerne an den <a href="https://gkv-bund.de/" target="_blank">GKV-Spitzenverband</a> wenden und sich damit politisch für Frauen- und Familiengesundheit engagieren.</p>
